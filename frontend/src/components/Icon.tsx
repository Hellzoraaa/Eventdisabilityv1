/** Ubah nama apa pun (Material atau Feather) menjadi nama ikon Feather yang tersedia. */
export function resolveFeatherName(name: string): string {
  const raw = String(name || '').trim();
  if (FEATHER_PATHS[raw]) return raw;
  const mapped = MATERIAL_TO_FEATHER[raw];
  if (mapped && FEATHER_PATHS[mapped]) return mapped;
  const dashed = raw.replace(/_/g, '-');
  if (FEATHER_PATHS[dashed]) return dashed;
  return 'circle';
}

/** Markup <svg> sebagai string, untuk tempat yang bukan JSX (mis. penanda Leaflet). */
export function featherSvgString(name: string, size = 20, strokeWidth = 2): string {
  const inner = FEATHER_PATHS[resolveFeatherName(name)];
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
}

export interface IconProps extends Omit<React.SVGProps<SVGSVGElement>, 'name' | 'ref'> {
  /** Nama ikon Feather (mis. 'book-open') atau nama lama Material (mis. 'menu_book'). */
  name: string;
  strokeWidth?: number;
}

